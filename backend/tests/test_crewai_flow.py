from types import SimpleNamespace

from onboardflow.adapters.catalogs.json_catalog import JsonCatalogAdapter
from onboardflow.adapters.crewai.orchestrator import LiveCrewAIOnboardingFlow
from onboardflow.config.settings import Settings
from onboardflow.domain.models import (
    CommunicationDraft,
    EmployeeOnboardingInput,
    ItemStatus,
    OnboardingRun,
    ResultItem,
    SpecialistOutput,
    ValidationResult,
)


class FakeProcess:
    sequential = "sequential"


class FakeLLM:
    def __init__(self, **kwargs):
        self.kwargs = kwargs


class FakeAgent:
    def __init__(self, **kwargs):
        self.kwargs = kwargs


class FakeTask:
    def __init__(self, **kwargs):
        self.kwargs = kwargs
        self.config = kwargs["config"]
        self.output = None


class FakeCrew:
    def __init__(self, **kwargs):
        self.tasks = kwargs["tasks"]

    def kickoff(self, inputs):
        assert "employee_json" in inputs
        for task in self.tasks:
            task_id = task.config["description"].split("Task id: ", 1)[1].split(".", 1)[0]
            task.output = SimpleNamespace(
                pydantic=_specialist_output(task_id),
                json_dict=None,
                raw="",
            )


def _specialist_output(task_id: str) -> SpecialistOutput:
    agent_names = {
        "validate_employee_input": "HR Intake",
        "generate_document_checklist": "Compliance",
        "generate_it_checklist": "IT Provisioning",
        "generate_training_path": "Training",
        "draft_stakeholder_messages": "Communication",
    }
    items = []
    communications = []
    if task_id == "generate_document_checklist":
        items = [
            ResultItem(
                title="Crew document",
                ownerRole="RH",
                status=ItemStatus.PENDING,
                rationale="Generated by fake CrewAI task.",
            )
        ]
    if task_id == "draft_stakeholder_messages":
        communications = [
            CommunicationDraft(
                audience="hr",
                subject="Crew subject",
                body="Crew body pending human review.",
            )
        ]
    return SpecialistOutput(
        taskId=task_id,
        agentName=agent_names[task_id],
        status="done",
        summary=f"{task_id} completed",
        items=items,
        communications=communications,
        inputSources=["employee_input", "local_catalogs", "crewai"],
        qualityChecks=["json_schema_valid", "human_review_required"],
    )


def test_live_crewai_flow_executes_crew_and_normalizes_plan(monkeypatch, employee_payload):
    employee = EmployeeOnboardingInput.model_validate(employee_payload)
    flow = LiveCrewAIOnboardingFlow(
        JsonCatalogAdapter(),
        Settings(onboarding_flow_mode="crewai"),
    )
    monkeypatch.setattr(
        flow,
        "_import_crewai",
        lambda: {
            "Agent": FakeAgent,
            "Crew": FakeCrew,
            "LLM": FakeLLM,
            "Process": FakeProcess,
            "Task": FakeTask,
        },
    )

    outputs, plan = flow.execute(
        OnboardingRun(),
        employee,
        ValidationResult(status="complete"),
    )

    assert len(outputs) == 5
    assert outputs[0].input_sources == ["employee_input", "local_catalogs", "crewai"]
    assert plan.required_documents[0].title == "Documento de identificacao"
    assert all(item.title != "Crew document" for item in plan.it_checklist)
    assert plan.communications[0].subject == "Crew subject"
    assert plan.status == "ready_for_review"
